def process_files(file_list):
    raw_features_list = []
    residuals_list = []

    for f in file_list:
        try:
            df = pd.read_csv(f, index_col=0, header=None).T
        except:
            df = pd.read_csv(f, index_col=0, header=None, sep=r'\s+').T
        df = df.reset_index(drop=True).astype(float)

        q = df[Q_COLS].values
        qd = df[QD_COLS].values
        qdd = df[QDD_COLS].values
        tau_true = df[TAU_COLS].values

        # Get DeLaN prediction
        _, tau_delan, _, _ = delan_model(params, None, jnp.array(q), jnp.array(qd), jnp.array(qdd), jnp.zeros_like(q))
        tau_delan = np.array(tau_delan)

        # Calculate Target (Residual Error)
        tau_res = tau_true - tau_delan

        # Features: [q, qd, qdd, tau_delan]
        features = np.concatenate([q, qd, qdd, tau_delan], axis=1)

        raw_features_list.append(features)
        residuals_list.append(tau_res)

    return raw_features_list, residuals_list

