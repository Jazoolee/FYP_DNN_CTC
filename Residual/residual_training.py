def create_windows(features_list, residuals_list, scaler):
    X_seq, y_seq = [], []
    for feats, res in zip(features_list, residuals_list):
        feats_scaled = scaler.transform(feats)
        for i in range(len(feats_scaled) - SEQ_LEN + 1):
            X_seq.append(feats_scaled[i : i + SEQ_LEN])
            y_seq.append(res[i + SEQ_LEN - 1]) # Target is the residual at the last timestep
    return np.array(X_seq), np.array(y_seq)

