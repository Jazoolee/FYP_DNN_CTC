# 5. PyTorch Dataset & DataLoader
class RobotDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.FloatTensor(X)
        self.y = torch.FloatTensor(y)
    def __len__(self):
        return len(self.X)
    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

train_loader = DataLoader(RobotDataset(X_train, y_train), batch_size=BATCH_SIZE, shuffle=True)
val_loader = DataLoader(RobotDataset(X_val, y_val), batch_size=BATCH_SIZE, shuffle=False)

# 6. GRU Model Definition
class GRUResidual(nn.Module):
    def __init__(self):
        super().__init__()
        self.gru = nn.GRU(input_size=INPUT_DIM, hidden_size=HIDDEN_DIM,
                          num_layers=N_LAYERS, batch_first=True, dropout=0.1)
        self.fc = nn.Linear(HIDDEN_DIM, OUTPUT_DIM)

    def forward(self, x):
        h, _ = self.gru(x)
        # Take the output of the last timestep in the sequence
        return self.fc(h[:, -1, :])

model = GRUResidual().to(device)
criterion = nn.MSELoss()
optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE, weight_decay=1e-4)

