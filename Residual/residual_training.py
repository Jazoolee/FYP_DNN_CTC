# 1. Define the Attention Architecture
class GRUAttentionResidual(nn.Module):
    def __init__(self):
        super().__init__()
        self.gru = nn.GRU(input_size=INPUT_DIM, hidden_size=HIDDEN_DIM,
                          num_layers=N_LAYERS, batch_first=True, dropout=0.1)

        # Attention specific layers
        self.W_a = nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False)
        self.v_a = nn.Linear(HIDDEN_DIM, 1, bias=False)

        self.fc = nn.Linear(HIDDEN_DIM, OUTPUT_DIM)

    def forward(self, x):
        # H shape: (batch_size, seq_len, hidden_dim)
        H, _ = self.gru(x)

        # Calculate attention scores
        # scores shape: (batch_size, seq_len)
        scores = self.v_a(torch.tanh(self.W_a(H))).squeeze(-1)

        # Calculate attention weights (alpha)
        alpha = torch.softmax(scores, dim=1)

        # Calculate context vector (weighted sum of hidden states)
        context = (alpha.unsqueeze(-1) * H).sum(dim=1)

        return self.fc(context)

